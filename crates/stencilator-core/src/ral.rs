use serde::Serialize;

use crate::colour::{Rgb, srgb_to_lab};

/// A nearest RAL Classic code and its approximate sRGB swatch.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
pub struct Match {
    /// The four-digit RAL code.
    pub code: u16,
    /// An unofficial sRGB approximation.
    #[serde(serialize_with = "crate::colour::hex")]
    pub colour: Rgb,
}

pub(crate) fn nearest(colour: Rgb) -> Match {
    let lab = srgb_to_lab(colour);
    let mut best = Match { code: 1000, colour: [0xcd, 0xba, 0x88] };
    let mut distance = f64::INFINITY;
    for (code, hex) in CLASSIC {
        let [_, red, green, blue] = hex.to_be_bytes();
        let colour = [red, green, blue];
        let [l, a, b] = srgb_to_lab(colour);
        let [dl, da, db] = [l - lab[0], a - lab[1], b - lab[2]];
        let squared = dl * dl + da * da + db * db;
        if squared < distance {
            best = Match { code, colour };
            distance = squared;
        }
    }
    best
}

